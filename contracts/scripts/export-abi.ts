import hre from "hardhat";
import { writeFileSync } from "fs";
import { join } from "path";

async function main() {
  const { abi } = await hre.artifacts.readArtifact("Quiz2Earn");
  const out = join(__dirname, "../../web/src/lib/abi.ts");
  writeFileSync(out, `// Generated by contracts/scripts/export-abi.ts. Do not edit.\nexport const quiz2EarnAbi = ${JSON.stringify(abi, null, 2)} as const;\n`);
  console.log(`ABI written to ${out}`);
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
